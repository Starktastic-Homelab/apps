HEADER = ("# Generated by scripts/homepage/generate.py from homepage/catalog.yaml. Do not edit.\n"
          "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: homepage-config\n  namespace: operations\ndata:\n")


class Base(unittest.TestCase):
    def setUp(self):
        self._d = tempfile.TemporaryDirectory()
        self.addCleanup(self._d.cleanup)

    def repo(self, edit=None, **kw):
        cat = copy.deepcopy(MIN_CATALOG)
        if edit:
            edit(cat)
        return make_repo(Path(self._d.name), cat, **kw)


def desc(text):
    return lambda c: c["tiles"]["a"].__setitem__("description", text)


class TestPlaceholders(Base):
    def test_rule16_braces(self):
        for bad in ("{{ x }}", "a }} b"):
            with self.subTest(bad=bad), self.assertRaisesRegex(CatalogError, r"^pages\.household:"):
                render_all(self.repo(desc(bad)))
        render_all(self.repo(desc("see pull/{number}"), pages={"household": {"custom.css": "a { b }\n"}}))

    def test_rule17_sealed_names_both_ways(self):
        with self.assertRaisesRegex(CatalogError, r"^pages\.household: .*HOMEPAGE_VAR_A"):
            render_all(self.repo(desc("{{HOMEPAGE_VAR_A}}"), sealed={"admin": ["HOMEPAGE_VAR_A"]}))
        with self.assertRaisesRegex(CatalogError, r"^pages\.admin: .*HOMEPAGE_VAR_B"):
            render_all(self.repo(sealed={"admin": ["HOMEPAGE_VAR_B"]}))
        settings = "title: T\nkey: '{{HOMEPAGE_VAR_C}}'\n"
        render_all(self.repo(sealed={"household": ["HOMEPAGE_VAR_C"]},
                             pages={"household": {"settings.yaml": settings}}))

    def test_missing_secrets_raises(self):
        repo = self.repo()
        (repo / "services/operations/homepage/manifests/templates/secrets.yaml").unlink()
        with self.assertRaisesRegex(CatalogError, r"^pages\.household:"):
            check_placeholders(repo, "household", "")


class TestDump(Base):
    def test_rule18_wrapper(self):
        repo = self.repo(desc("Films · שלום · café"))
        text = dump_page("household", build_page(repo, load_catalog(repo), "household"))
        self.assertTrue(text.startswith(HEADER))
        self.assertIn('  docker.yaml: ""\n', text)
        self.assertIn("  services.yaml: |\n    - G:\n", text)
        self.assertIn("Films · שלום · café", text)
        self.assertTrue(text.endswith("\n") and not text.endswith("\n\n"))
        repo2 = self.repo(desc("Films · שלום · café"), pages={"household": {"custom.css": "a { b }\n\n\n"}})
        text2 = dump_page("household", build_page(repo2, load_catalog(repo2), "household"))
        self.assertIn("  custom.css: |\n    a { b }\n  kubernetes.yaml: |\n", text2)
        self.assertEqual(render_all(repo2), render_all(repo2))

    def test_rule19_escape_roundtrip(self):
        self.assertEqual(helm_escape("k: {{HOMEPAGE_VAR_X}}"), 'k: {{ "{{" }}HOMEPAGE_VAR_X{{ "}}" }}')
        widget = {"audience": "household", "type": "x", "key": "{{HOMEPAGE_VAR_K}}", "url": "http://h/?k={{HOMEPAGE_VAR_K}}&a=1"}
        repo = self.repo(lambda c: c["tiles"]["a"].__setitem__("widgets", [widget]),
                         sealed={p: ["HOMEPAGE_VAR_K"] for p in ("household", "admin")})
        cat = load_catalog(repo)
        for page, text in zip(("household", "admin"), render_all(repo).values()):
            self.assertIn('{{ "{{" }}HOMEPAGE_VAR_K{{ "}}" }}', text)
            cm = yaml.safe_load(text.replace('{{ "{{" }}', "{{").replace('{{ "}}" }}', "}}"))
            for key, val in build_page(repo, cat, page).items():
                if not isinstance(val, str):
                    self.assertEqual(yaml.safe_load(cm["data"][key]), val, key)


class TestCli(Base):
    def run_main(self, argv, repo):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = main(argv, repo)
        return code, out.getvalue() + err.getvalue()

    def test_check_and_write(self):
        repo = self.repo()
        code, out = self.run_main(["--check"], repo)
        self.assertEqual(code, 1)  # nothing written yet
        self.assertEqual(self.run_main([], repo)[0], 0)
        for page in ("household", "admin"):
            self.assertTrue(output_path(repo, page).is_file())
        self.assertEqual(output_path(repo, "household"),
                         repo / "homepage/staged/services/operations/homepage/manifests/templates/configmap.yaml")
        self.assertEqual(self.run_main(["--check"], repo), (0, ""))
        cat = (repo / "homepage/catalog.yaml").read_text().replace("name: A", "name: A\n    description: new")
        (repo / "homepage/catalog.yaml").write_text(cat)
        code, out = self.run_main(["--check"], repo)
        self.assertEqual(code, 1)
        self.assertIn("+          description: new", out)
        self.assertIn("run: python3 scripts/homepage/generate.py", out)

    def test_catalog_error_exits_1(self):
        repo = self.repo(desc("{{ x }}"))
        code, out = self.run_main([], repo)
        self.assertEqual(code, 1)
        self.assertIn("pages.household:", out)

    def test_flags_exclusive(self):
        with self.assertRaises(SystemExit):
            self.run_main(["--check", "--inventory"], self.repo())

    def test_cwd_independent(self):
        repo = self.repo()
        self.run_main([], repo)
        old = os.getcwd()
        with tempfile.TemporaryDirectory() as d:
            os.chdir(d)
            try:
                self.assertEqual(self.run_main(["--check"], repo), (0, ""))
            finally:
                os.chdir(old)


class TestInventory(Base):
    def test_inventory(self):
        def edit(c):
            c["tiles"]["a"]["widgets"] = [
                {"audience": "household", "type": "calendar", "refreshInterval": 600,
                 "integrations": [{"type": "ical", "name": "TV", "url": "http://ics"}]},
                {"audience": "household", "type": "sonarr", "url": "http://so", "highlight": {"q": 1}}]
            c["bookmarks"] = {"gh": {"name": "GitHub", "audience": "household-only", "href": "https://gh"}}
            c["info"] = [{"audience": "household", "datetime": {"text_size": "xl"}}]
            c["pages"]["household"]["tabs"].append(
                {"name": "Play Time", "groups": [{"name": "Links", "items": ["gh"]}]})
        inv = inventory(self.repo(edit))["household"]
        self.assertEqual(inv["tabs"], [{"name": "Main", "slug": "main"}, {"name": "Play Time", "slug": "play-time"}])
        self.assertEqual(inv["groups"], [{"name": "G", "tab": "Main", "parents": []},
                                         {"name": "Links", "tab": "Play Time", "parents": []}])
        self.assertEqual(inv["tiles"], [{
            "id": "a", "name": "A", "group": "G", "href": "https://a.example",
            "widgets": ["calendar", "sonarr"], "urls": ["http://ics", "http://so"],
            "highlight": [None, {"q": 1}], "refreshInterval": [600, None]}])
        self.assertEqual(inv["bookmarks"], [{"id": "gh", "name": "GitHub", "group": "Links", "href": "https://gh"}])
        self.assertEqual(inv["info"], ["datetime"])
        code, out = TestCli.run_main(self, ["--inventory"], self.repo(edit))
        self.assertEqual(code, 0)
        self.assertIn('"play-time"', out)


